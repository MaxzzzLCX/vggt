"""
This script infers a height distribution from the point map generated by VGGT.
"""

import numpy as np
import argparse
import open3d as o3d
import matplotlib.pyplot as plt
from pathlib import Path

def parse_args():
    parser = argparse.ArgumentParser(
        description="Infer height distribution from point map"
    )
    parser.add_argument(
        "--pointmap_path",
        type=str,
        required=True,
        help="Path to the input point map file (e.g., .npy or .ply)",
    )
    parser.add_argument(
        "--top_view_axis",
        type=str,
        default="z",
        choices=["x", "y", "z"],
        help="To decide which view is the top-down view (default: z axis as height)",
    )

    parser.add_argument("--resolution", type=int, default=300, help="Number of 'bins' along each axis")
    
    return parser.parse_args()

